# Ask for two numbers
# Print their sum and product

num_1 = int(input("Number 1: "))
num_2 = int(input("Number 2: "))
sum = num_1 + num_2
product = num_1 * num_2

print(f"The sum of the numbers: {sum}")
print(f"The product of the numbers: {product}")

